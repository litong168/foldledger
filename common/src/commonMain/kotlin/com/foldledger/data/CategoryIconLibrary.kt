    /**
     * 全部图标（同一 Emoji 只留一条），供「搜索」用。
     *
     * 注意是**合并关键词**而不是取第一条：同一个 Emoji 常出现在多个分组里
     * （比如 🧾 既在「水电物业」是账单、又在「金融理财」是报销），
     * 只保留第一条会让「报销」这种词搜不到 —— 这是单测抓出来的真实缺陷。
     */
    val all: List<PresetIcon> by lazy {
        groups.flatMap { it.icons }
            .groupBy { it.emoji }
            .map { (emoji, list) -> PresetIcon(emoji, list.joinToString(" ") { it.keywords }) }
    }

    /**
     * 关键词搜索。空白查询返回 null，调用方据此切回「按分组浏览」。
     * 命中规则：关键词包含查询串，或 emoji 本身相等。
     */
    fun search(query: String): List<PresetIcon>? {
        val q = query.trim()
        if (q.isEmpty()) return null
        return all.filter { it.keywords.contains(q, ignoreCase = true) || it.emoji == q }
    }
