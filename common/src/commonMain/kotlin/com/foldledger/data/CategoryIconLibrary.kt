 * 纯 Emoji 方案，不引任何图标资源包 —— 理由：
 *  - `material-icons-extended` 会把方法数顶上去、编译时间暴涨，而且图标是单色线条，
 *    和记账 App「彩色、一眼认得出」的诉求不搭
 *  - Emoji 由系统字体渲染，**零体积、全彩、任意尺寸都不糊**，在任何 Android 版本上都一致
 *
 * 每组都带中文关键词，所以选择器里可以按「加油」「疫苗」「房贷」这种词直接搜到。
 */
